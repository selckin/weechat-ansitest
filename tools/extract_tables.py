#!/usr/bin/env python3
"""Copy WeeChat's color tables into ansitest/tables_data.py.

Usage: tools/extract_tables.py WEECHAT_SOURCE_DIR
"""

import pathlib
import re
import subprocess
import sys

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "ansitest" / "tables_data.py"


def array_body(source: str, declaration: str) -> str:
    match = re.search(re.escape(declaration) + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        sys.exit(f"array not found: {declaration}")
    return re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip())
    src = pathlib.Path(sys.argv[1])
    gui = (src / "src" / "gui" / "gui-color.c").read_text()
    irc = (src / "src" / "plugins" / "irc" / "irc-color.c").read_text()
    term256 = [int(x, 16) for x in
               re.findall(r"0x[0-9a-fA-F]+", array_body(gui, "int gui_color_term256"))]
    term2irc = [int(x) for x in
                re.findall(r"\d+", array_body(irc, "char irc_color_term2irc"))]
    if len(term256) != 256 or len(term2irc) != 16:
        sys.exit(f"unexpected sizes: {len(term256)}, {len(term2irc)}")
    version = subprocess.run(["git", "-C", str(src), "describe", "--always", "--tags"],
                             capture_output=True, text=True).stdout.strip() or "unknown"
    rows = [", ".join(f"0x{value:06x}" for value in term256[i:i + 6])
            for i in range(0, 256, 6)]
    OUTPUT.write_text(
        f'"""Generated by tools/extract_tables.py from WeeChat {version}: do not edit."""\n'
        "\n"
        "# gui_color_term256 (src/gui/gui-color.c)\n"
        "TERM256 = [\n" + "".join(f"    {row},\n" for row in rows) + "]\n"
        "\n"
        "# irc_color_term2irc (src/plugins/irc/irc-color.c)\n"
        f"TERM2IRC = {term2irc}\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
